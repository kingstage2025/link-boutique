@app.route("/register", methods=("GET", "POST"))
def register():
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")
        if not email or "@" not in email:
            flash("Saisissez une adresse e-mail valide.", "danger")
        elif len(password) < 8:
            flash("Le mot de passe doit contenir au moins 8 caractères.", "danger")
        else:
            try:
                db = get_db()
                execute(
                    "INSERT INTO users (email, password_hash) VALUES (?, ?)",
                    (email, generate_password_hash(password)),
                )
                db.commit()
                flash("Compte créé. Vous pouvez maintenant vous connecter.", "success")
                return redirect(url_for("login"))
            except sqlite3.IntegrityError:
                flash("Cette adresse e-mail est déjà utilisée.", "danger")
    return render_template("login.html", mode="register")


@app.route("/login", methods=("GET", "POST"))
def login():
    if request.method == "POST":
        user = execute(
            "SELECT * FROM users WHERE email = ?", (request.form.get("email", "").strip().lower(),)
        ).fetchone()
        if user is None or not check_password_hash(user["password_hash"], request.form.get("password", "")):
            flash("E-mail ou mot de passe incorrect.", "danger")
        else:
            session.clear()
            session["user_id"] = user["id"]
            return redirect(url_for("dashboard"))
    return render_template("login.html", mode="login")


@app.post("/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


@app.route("/dashboard")
@login_required
def dashboard():
    month = request.args.get("month", date.today().strftime("%Y-%m"))
    start, end = month_bounds(month)
    db = get_db()
    totals = execute(
        """
        SELECT kind, COALESCE(SUM(amount), 0) AS total
        FROM transactions
        WHERE user_id = ? AND transaction_date >= ? AND transaction_date < ?
        GROUP BY kind
        """,
        (g.user["id"], start, end),
    ).fetchall()
    total_map = {row["kind"]: row["total"] for row in totals}
    expenses = execute(
        """
        SELECT category, SUM(amount) AS total
        FROM transactions
        WHERE user_id = ? AND kind = 'expense'
          AND transaction_date >= ? AND transaction_date < ?
        GROUP BY category ORDER BY total DESC
        """,
        (g.user["id"], start, end),
    ).fetchall()
    betting_total = execute(
        """
        SELECT COALESCE(SUM(amount), 0) FROM transactions
        WHERE user_id = ? AND kind = 'expense' AND category = 'Paris sportifs'
          AND transaction_date >= ? AND transaction_date < ?
        """,
        (g.user["id"], start, end),
    ).fetchone()[0]
    recent = execute(
        "SELECT * FROM transactions WHERE user_id = ? ORDER BY transaction_date DESC, id DESC LIMIT 8",
        (g.user["id"],),
    ).fetchall()
    budgets = execute(
        "SELECT * FROM budgets WHERE user_id = ? AND month = ?", (g.user["id"], month)
    ).fetchall()
    spent_by_category = {
        row["category"]: row["total"]
        for row in execute(
            """
            SELECT category, SUM(amount) AS total FROM transactions
            WHERE user_id = ? AND kind = 'expense'
              AND transaction_date >= ? AND transaction_date < ?
            GROUP BY category
            """,
            (g.user["id"], start, end),
        ).fetchall()
    }
    budget_status = [
        {**dict(budget), "spent": spent_by_category.get(budget["category"], 0)}
        for budget in budgets
    ]
    return render_template(
        "dashboard.html",
        month=month,
        income=total_map.get("income", 0),
        expenses_total=total_map.get("expense", 0),
        balance=total_map.get("income", 0) - total_map.get("expense", 0),
        betting_total=betting_total,
        expenses=expenses,
        recent=recent,
        budget_status=budget_status,
    )


@app.route("/transactions", methods=("GET", "POST"))
@login_required
def transactions():
    db = get_db()
    if request.method == "POST":
        kind = request.form.get("kind", "expense")
        description = request.form.get("description", "").strip()
        category = request.form.get("category") or suggest_category(description, kind)
        try:
            amount = float(request.form.get("amount", "0"))
            transaction_date = datetime.strptime(
                request.form.get("transaction_date", ""), "%Y-%m-%d"
            ).date().isoformat()
            if kind not in {"income", "expense"} or amount <= 0:
                raise ValueError
        except (TypeError, ValueError):
            flash("Vérifiez le type, le montant et la date.", "danger")
        else:
            execute(
                """
                INSERT INTO transactions
                    (user_id, kind, amount, category, description, transaction_date)
                VALUES (?, ?, ?, ?, ?, ?)
                """,
                (g.user["id"], kind, amount, category, description, transaction_date),
            )
            db.commit()
            flash("Transaction ajoutée.", "success")
            return redirect(url_for("transactions"))
    rows = execute(
        "SELECT * FROM transactions WHERE user_id = ? ORDER BY transaction_date DESC, id DESC",
        (g.user["id"],),
    ).fetchall()
    return render_template(
        "transactions.html",
        transactions=rows,
        categories=CATEGORIES,
        today=date.today().isoformat(),
    )


