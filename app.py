@app.route("/budgets", methods=("GET", "POST"))
@login_required
def budgets():
    month = request.values.get("month", date.today().strftime("%Y-%m"))
    db = get_db()
    if request.method == "POST":
        try:
            amount = float(request.form.get("amount", "0"))
            category = request.form["category"]
            if amount <= 0 or category not in CATEGORIES:
                raise ValueError
            execute(
                """
                INSERT INTO budgets (user_id, category, amount, month) VALUES (?, ?, ?, ?)
                ON CONFLICT(user_id, category, month)
                DO UPDATE SET amount = excluded.amount
                """,
                (g.user["id"], category, amount, month),
            )
            db.commit()
            flash("Budget enregistré.", "success")
        except (KeyError, ValueError):
            flash("Saisissez une catégorie et un montant valides.", "danger")
        return redirect(url_for("budgets", month=month))
    rows = execute(
        "SELECT * FROM budgets WHERE user_id = ? AND month = ? ORDER BY category",
        (g.user["id"], month),
    ).fetchall()
    start, end = month_bounds(month)
    budget_status = []
    for row in rows:
        spent = execute(
            """
            SELECT COALESCE(SUM(amount), 0) FROM transactions
            WHERE user_id = ? AND kind = 'expense' AND category = ?
              AND transaction_date >= ? AND transaction_date < ?
            """,
            (g.user["id"], row["category"], start, end),
        ).fetchone()[0]
        budget_status.append({**dict(row), "spent": spent})
    return render_template(
        "budgets.html", budgets=budget_status, month=month, categories=CATEGORIES
    )


@app.get("/export/csv")
@login_required
def export_csv():
    rows = execute(
        """
        SELECT transaction_date, kind, category, description, amount
        FROM transactions WHERE user_id = ? ORDER BY transaction_date DESC
        """,
        (g.user["id"],),
    ).fetchall()
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["date", "type", "categorie", "description", "montant"])
    writer.writerows(
        (row["transaction_date"], row["kind"], row["category"], row["description"], row["amount"])
        for row in rows
    )
    return send_file(
        io.BytesIO(output.getvalue().encode("utf-8-sig")),
        mimetype="text/csv",
        as_attachment=True,
        download_name="rapport-finances.csv",
    )


@app.get("/export/xlsx")
@login_required
def export_xlsx():
    try:
        from openpyxl import Workbook
    except ImportError:
        flash("L'export Excel nécessite l'installation des dépendances.", "danger")
        return redirect(url_for("dashboard"))

    rows = execute(
        """
        SELECT transaction_date, kind, category, description, amount
        FROM transactions WHERE user_id = ? ORDER BY transaction_date DESC
        """,
        (g.user["id"],),
    ).fetchall()
    workbook = Workbook()
    sheet = workbook.active
    sheet.title = "Transactions"
    sheet.append(["Date", "Type", "Catégorie", "Description", "Montant (€)"])
    for row in rows:
        sheet.append(
            [row["transaction_date"], row["kind"], row["category"], row["description"], row["amount"]]
        )
    sheet.freeze_panes = "A2"
    sheet.auto_filter.ref = sheet.dimensions
    for column in sheet.columns:
        width = max(len(str(cell.value or "")) for cell in column) + 2
        sheet.column_dimensions[column[0].column_letter].width = min(width, 35)
    output = io.BytesIO()
    workbook.save(output)
    output.seek(0)
    return send_file(
        output,
        mimetype="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        as_attachment=True,
        download_name="rapport-finances.xlsx",
    )


