def get_db() -> sqlite3.Connection:
    if "db" not in g:
        if app.config["DATABASE_URL"]:
            import psycopg2
            from psycopg2.extras import DictCursor

            database_url = app.config["DATABASE_URL"].replace(
                "postgres://", "postgresql://", 1
            )
            g.db = psycopg2.connect(database_url, cursor_factory=DictCursor)
        else:
            g.db = sqlite3.connect(app.config["DATABASE"])
            g.db.row_factory = sqlite3.Row
            g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


def execute(sql: str, parameters=()):
    """Use the same query source for local SQLite and hosted PostgreSQL."""
    if app.config["DATABASE_URL"]:
        sql = sql.replace("?", "%s")
    return get_db().execute(sql, parameters)


@app.teardown_appcontext
def close_db(_error: BaseException | None) -> None:
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db() -> None:
    db = get_db()
    schema = """
        CREATE TABLE IF NOT EXISTS users (
            id {id_type} PRIMARY KEY,
            email TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS transactions (
            id {id_type} PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            kind TEXT NOT NULL CHECK(kind IN ('income', 'expense')),
            amount REAL NOT NULL CHECK(amount > 0),
            category TEXT NOT NULL,
            description TEXT NOT NULL DEFAULT '',
            transaction_date TEXT NOT NULL,
            created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS budgets (
            id {id_type} PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            category TEXT NOT NULL,
            amount REAL NOT NULL CHECK(amount > 0),
            month TEXT NOT NULL,
            UNIQUE(user_id, category, month)
        );
        """.format(
        id_type=(
            "INTEGER GENERATED BY DEFAULT AS IDENTITY"
            if app.config["DATABASE_URL"]
            else "INTEGER"
        )
    )
    if app.config["DATABASE_URL"]:
        with db.cursor() as cursor:
            cursor.execute(schema)
    else:
        db.executescript(schema)
    db.commit()


@app.before_request
def prepare_request() -> None:
    init_db()
    g.user = None
    user_id = session.get("user_id")
    if user_id is not None:
        g.user = execute(
            "SELECT id, email FROM users WHERE id = ?", (user_id,)
        ).fetchone()


def login_required(view):
    @wraps(view)
    def wrapped_view(*args, **kwargs):
        if g.user is None:
            flash("Connectez-vous pour accéder à cette page.", "warning")
            return redirect(url_for("login"))
        return view(*args, **kwargs)

    return wrapped_view


def suggest_category(description: str, kind: str) -> str:
    if kind == "income":
        return "Chantier" if "chantier" in description.lower() else "Autres revenus"
    keywords = {
        "Paris sportifs": ("pari", "paris", "bet", "cote", "cotes", "football", "foot"),
        "Beignets": ("beignet", "beignets", "pain", "petit déjeuner", "petit dejeuner"),
        "Transport": ("moto", "taxi", "essence", "bus", "transport"),
        "Alimentation": ("courses", "restaurant", "repas", "marché", "marche"),
    }
    text = description.lower()
    for category, terms in keywords.items():
        if any(term in text for term in terms):
            return category
    return "Autres"


def month_bounds(month: str) -> tuple[str, str]:
    year, month_number = (int(value) for value in month.split("-"))
    if month_number == 12:
        next_month = date(year + 1, 1, 1)
    else:
        next_month = date(year, month_number + 1, 1)
    return f"{year:04d}-{month_number:02d}-01", next_month.isoformat()


